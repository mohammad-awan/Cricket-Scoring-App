"""Controlled object storage for uploaded files.

Only this module touches the media directory. Object keys are generated by
the application (never taken from user input) and are always resolved
inside the storage root, so a key can never escape it.
"""

from __future__ import annotations
import os
import tempfile
from functools import lru_cache
from pathlib import Path, PurePosixPath
from app.core.config import get_settings


class LocalObjectStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def path_for(self, key: str) -> Path:
        relative = PurePosixPath(key)

        if relative.is_absolute() or ".." in relative.parts or not relative.parts:
            raise ValueError("Invalid object key")

        path = (self.root / Path(*relative.parts)).resolve()
        if not path.is_relative_to(self.root):
            raise ValueError("Invalid object key")

        return path

    def put(self, key: str, data: bytes) -> None:
        """Write atomically: readers never see a partially written file."""

        path = self.path_for(key)
        path.parent.mkdir(parents=True, exist_ok=True)

        if path.exists():
            # Content-addressed keys: same key means same bytes.
            return

        handle, temp_name = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
        try:
            with os.fdopen(handle, "wb") as file:
                file.write(data)
            os.replace(temp_name, path)
        except BaseException:
            Path(temp_name).unlink(missing_ok=True)
            raise

    def exists(self, key: str) -> bool:
        return self.path_for(key).is_file()


@lru_cache
def get_object_storage() -> LocalObjectStorage:
    root = Path(get_settings().media_root)
    if not root.is_absolute():
        root = Path(__file__).resolve().parents[2] / root

    return LocalObjectStorage(root)
